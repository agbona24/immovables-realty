// Helper function to get blog post by ID
export const getBlogPostById = (id: string): BlogPost | undefined => {
  return blogPosts.find((post) => post.id === id);
};

// Helper function to get related posts (same category, different id)
export const getRelatedPosts = (
  currentId: string,
  limit: number = 3
): BlogPost[] => {
  const currentPost = getBlogPostById(currentId);
  if (!currentPost) return [];

  return blogPosts
    .filter(
      (post) =>
        post.category === currentPost.category && post.id !== currentId
    )
    .slice(0, limit);
};
